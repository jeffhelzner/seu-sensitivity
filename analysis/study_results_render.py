# ---------------------------------------------------------------------------- formatting

def num(value, digits=3):
    if value is None:
        return "—"
    text = f"{value:.{digits}f}"
    if text.lstrip("-").strip("0.") == "":
        text = text.lstrip("-")
    return text.replace("-", "−")


def interval(row, digits=3, transform=None):
    lower, upper = row["lower_90"], row["upper_90"]
    if transform:
        lower, upper = transform(lower), transform(upper)
    return f"[{num(lower, digits)}, {num(upper, digits)}]"


def estimate(row, digits=3):
    return f"{num(row['median'], digits)} {interval(row, digits)}"


def ratio(row, digits=2):
    return f"{num(math.exp(row['median']), digits)} {interval(row, digits, math.exp)}"


def pct(numerator, denominator, digits=1):
    return f"{100 * numerator / denominator:.{digits}f}%"


def count(value):
    return f"{value:,}"


def money(value):
    return f"${value:,.2f}"


def decision(value):
    return DECISIONS[value]


def model_from(token):
    return UNDERSCORE[token]


def contrast_label(identifier):
    if identifier == "rq6_gamma_size":
        return "Menu-size slope (per added alternative)"
    if identifier == "rq1_openai_flagship_minus_small":
        return "OpenAI flagship − small (GPT-4o − GPT-4o-mini)"
    if identifier == "rq1_anthropic_flagship_minus_small":
        return "Anthropic flagship − small (Sonnet 4.5 − Haiku 4.5)"
    if identifier == "rq2_seu_maximizing_minus_neutral":
        return "SEU instruction − neutral"
    if identifier == "rq2_deliberative_minus_neutral":
        return "Deliberative instruction − neutral"
    if identifier.startswith("rq1_") and identifier.endswith("_minus_gpt_4o"):
        return f"{ARMS[model_from(identifier[4:-len('_minus_gpt_4o')])]} − GPT-4o"
    if identifier.startswith("rq5_") and identifier.endswith("_hiring_minus_procurement"):
        return f"{ARMS[model_from(identifier[4:-len('_hiring_minus_procurement')])]}: hiring − procurement"
    raise KeyError(identifier)


def cell_label(cell):
    return f"{ARMS[cell['model']]} / {PROMPT_TITLES[cell['prompt']]}"


def table(header, rows, caption=None, label=None, align=None):
    align = align or ["---"] * len(header)
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join(align) + "|"]
    lines += ["| " + " | ".join(str(cell) for cell in row) + " |" for row in rows]
    if caption:
        lines += ["", f": {caption}" + (f" {{#{label}}}" if label else "")]
    return "\n".join(lines) + "\n"


def left_right(columns_left, columns_right):
    return [":---"] * columns_left + ["---:"] * columns_right


# ---------------------------------------------------------------------------- derived quantities

def decision_index(evidence):
    return {group: {row["id"]: row for row in evidence["decisions"][group]} for group in GROUPS}


def detected(rows):
    return sum(row["decision"] != "not_detected" for row in rows)


def primary_rows(evidence, group):
    rows = evidence["decisions"][group]
    if group == "matched_rq5":
        return [row for row in rows if row["research_question"] == "RQ5"]
    return rows


def fit_row(evidence, group, variant):
    return next(row for row in evidence["fits"] if row["group"] == group and row["variant"] == variant)


def pairwise_probability(alpha, gap):
    return 1 / (1 + math.exp(-alpha * gap))


def illustration(evidence, group, cell_id):
    alpha = evidence["ceiling"][group]["cells"][cell_id]["quantiles"]["primary"]["alpha"]
    return {gap: {quantile: pairwise_probability(alpha[quantile], gap) for quantile in ("q05", "q50", "q95")}
            for gap in GAPS}


def cells_for(evidence, group, task=None):
    cells = evidence["ceiling"][group]["cells"]
    return [(cell_id, cell) for cell_id, cell in sorted(
        cells.items(), key=lambda item: (MODELS.index(item[1]["model"]), PROMPTS.index(item[1]["prompt"]),
                                         item[1]["task"]))
        if task is None or cell["task"] == task]


def a4_pool_row(evidence, group, task, size=None):
    return next(row for row in evidence["a4"]["pool"][group]["groups"] if row["task"] == task and row["menu_size"] == size)


def tasks(group):
    return ("venture", "hiring") if group == "matched_rq5" else (group,)


def task_title(group, task):
    if group == "matched_rq5":
        return "Matched procurement" if task == "venture" else "Matched hiring"
    return GROUP_TITLES[group]


