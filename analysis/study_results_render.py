def figure_inputs(evidence):
    """Canonical numerical inputs of every figure; their digest is what --check verifies."""
    index = decision_index(evidence)
    inputs = {"decisions": {group: [{key: row[key] for key in ("id", "median", "lower_90", "upper_90", "decision",
                                                               "rope_half_width")} for row in evidence["decisions"][group]]
                            for group in GROUPS}}
    inputs["cells"] = {group: {cell_id: {"model": cell["model"], "prompt": cell["prompt"], "task": cell["task"],
                                         "alpha": cell["quantiles"]["primary"]["alpha"],
                                         "ceiling": cell["classification"] == "finite_supremum_at_infinity"}
                               for cell_id, cell in evidence["ceiling"][group]["cells"].items()} for group in GROUPS}
    sensitivity = {}
    for group in GROUPS:
        rows = {}
        for identifier, row in index[group].items():
            estimates = {"primary": {key: row[key] for key in ("median", "lower_90", "upper_90")}}
            for kind in ("presentation", "utility"):
                for item in evidence["sensitivity"][group][kind]:
                    if item["id"] == identifier:
                        for variant, value in item["estimates"].items():
                            if variant != "primary":
                                estimates[variant] = {key: value[key] for key in ("median", "lower_90", "upper_90")}
            for variant in ("prior_L", "prior_H", "prior_S"):
                for item in evidence["prior"][group]["variants"][variant]["comparisons"]:
                    if item["id"] == identifier:
                        estimates[variant] = {key: item["alternative"][key] for key in ("median", "lower_90", "upper_90")}
            if group in POOLS:
                for item in evidence["stable"]["pools"][group]["comparison"]:
                    if item["id"] == identifier:
                        value = item["estimates"]["position_stable_subset"]
                        estimates["position_stable_subset"] = {key: value[key] for key in ("median", "lower_90", "upper_90")}
            rows[identifier] = {"rope": row["rope_half_width"], "estimates": estimates}
        sensitivity[group] = rows
    inputs["sensitivity"] = sensitivity
    inputs["repetition"] = {group: {cell_id: {"observed": cell["same_item"]["observed"],
                                              "q05": cell["same_item"]["replicated"]["q05"],
                                              "q95": cell["same_item"]["replicated"]["q95"],
                                              "model": evidence["ceiling"][group]["cells"][cell_id]["model"],
                                              "prompt": evidence["ceiling"][group]["cells"][cell_id]["prompt"],
                                              "task": evidence["ceiling"][group]["cells"][cell_id]["task"]}
                                    for cell_id, cell in evidence["a4"]["cells"][group].items() if "same_item" in cell}
                            for group in GROUPS}
    inputs["size"] = {f"{group}/{task}": {str(size): {name: {"observed": a4_pool_row(evidence, group, task, size)["statistics"][name]["observed"],
                                                             "q05": a4_pool_row(evidence, group, task, size)["statistics"][name]["replicated"]["q05"],
                                                             "q95": a4_pool_row(evidence, group, task, size)["statistics"][name]["replicated"]["q95"]}
                                                      for name in ("maximizer_fraction", "mean_regret")}
                                          for size in (2, 4, 6, 8)}
                      for group in GROUPS for task in tasks(group)}
    inputs["slices"] = {cell_id: {"grid": cell["slice"]["grid"], "difference": cell["slice"]["log_likelihood_difference"],
                                  "ceiling": cell["classification"] == "finite_supremum_at_infinity",
                                  "task": cell["task"], "model": cell["model"], "prompt": cell["prompt"],
                                  "t": cell["quantiles"]["primary"]["t"]}
                        for cell_id, cell in evidence["ceiling"]["matched_rq5"]["cells"].items() if "slice" in cell}
    inputs["positions"] = {group: [{"task": row["task"], "size": row["menu_size"], "presentation": row["presentation"],
                                    "position": row["position"], "observed": row["fraction"]["observed"],
                                    "q05": row["fraction"]["replicated"]["q05"], "q95": row["fraction"]["replicated"]["q95"],
                                    "flag": row["fraction"]["flag"]}
                                   for row in evidence["a4"]["positions"][group]] for group in POOLS}
    return inputs


def canonical_digest(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, separators=(",", ":"), allow_nan=False).encode()).hexdigest()


