    rows = []
    for row in evidence["fits"]:
        rows.append([GROUP_TITLES[row["group"]], VARIANT_TITLES[row["variant"]], count(row["observations"]), row["machine"],
                     num(row["max_rhat"], 4), f"{row['min_ess_bulk']:,.0f} / {row['min_ess_tail']:,.0f}",
                     num(row["min_ebfmi"], 2), row["divergences"], num(row["treedepth_saturated_share"], 1),
                     num(row["sample_minutes"], 1)])
    for pool in POOLS:
        row = evidence["stable"]["pools"][pool]
