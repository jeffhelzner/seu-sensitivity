def include_collection(evidence):
    collection = evidence["collection"]
    rows = [[size, count(row["eligible"]), row["unresolved"], pct(row["unresolved"], row["eligible"], 2)]
            for size, row in sorted(collection["unresolved_by_size"].items(), key=lambda item: int(item[0]))]
    total_eligible = sum(row["eligible"] for row in collection["unresolved_by_size"].values())
    total_unresolved = sum(row["unresolved"] for row in collection["unresolved_by_size"].values())
    rows.append(["All", count(total_eligible), total_unresolved, pct(total_unresolved, total_eligible, 2)])
    text = table(["Menu size", "Requests", "Unresolved", "Rate"], rows,
                 "Unresolved choice responses by menu size across all 36 cells. Unresolved responses are excluded "
                 "from the likelihood; none was repaired, imputed or recollected.", "tbl-unresolved-size",
                 left_right(1, 3))
    by_cell = sorted(collection["unresolved_by_cell"].items())
    metadata = {**evidence["ceiling"]["venture"]["cells"], **evidence["ceiling"]["hiring"]["cells"]}
    cell_rows = [[ARMS[metadata[cell]["model"]], PROMPT_TITLES[metadata[cell]["prompt"]],
                  GROUP_TITLES[metadata[cell]["pool"]], value, pct(value, 280)] for cell, value in by_cell]
    text += "\n" + table(["Arm", "Prompt", "Pool", "Unresolved of 280", "Rate"], cell_rows,
                         "Cells with at least one unresolved response. The frozen rule flags a cell above 10% "
                         "and excludes it above 30%; no cell reached either threshold.", "tbl-unresolved-cells",
                         left_right(3, 2))
    variants = collection["variants"]
    variant_rows = []
    for key, row in variants.items():
        group, variant = key.split("/")
        if variant not in ("primary", "presentation_1_only", "presentation_2_only"):
            continue
        variant_rows.append([GROUP_TITLES[group], VARIANT_TITLES[variant], row["cells"], count(row["observations"]),
                             row["excluded_observations"], row["rank"],
                             " / ".join(str(row["retained_by_size"][size]) for size in ("2", "4", "6", "8"))])
    text += "\n" + table(["Fit group", "Data", "Cells", "Retained", "Excluded", "Design rank", "Retained at sizes 2/4/6/8"],
                         variant_rows, "Retained analysis data. Utility and prior variants use exactly the full-data "
                         "observations of their group's primary dataset.", "tbl-retained", left_right(2, 5))
    return text


