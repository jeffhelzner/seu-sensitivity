def render_values(evidence):
    return ("# Generated by python -m analysis.study_results_evidence --write. Do not edit by hand.\n"
            + yaml.safe_dump(build_values(evidence), sort_keys=True, allow_unicode=True, width=1000))


def write_outputs(evidence):
    INCLUDES.mkdir(exist_ok=True)
    includes = build_includes(evidence)
    for stale in INCLUDES.glob("*.qmd"):
        if stale.stem not in includes:
            stale.unlink()
    for name, text in includes.items():
        (INCLUDES / f"{name}.qmd").write_text(text)
    VALUES.write_text(render_values(evidence))
    inputs, record = figure_record(evidence)
    outputs = plot_figures(inputs)
    record["png_sha256"] = {name: hashlib.sha256(path.read_bytes()).hexdigest() for name, path in sorted(outputs.items())}
    FIGURE_MANIFEST.write_text(json.dumps(record, indent=1, sort_keys=True) + "\n")


def check_outputs(evidence):
    includes = build_includes(evidence)
    present = {path.stem for path in INCLUDES.glob("*.qmd")}
    if present != set(includes):
        raise ValueError(f"Include set differs: missing {sorted(set(includes) - present)}, extra {sorted(present - set(includes))}")
    for name, text in includes.items():
        if (INCLUDES / f"{name}.qmd").read_text() != text:
            raise ValueError(f"_results/{name}.qmd differs from the supplement rendering")
    if VALUES.read_text() != render_values(evidence):
        raise ValueError("results_values.yml differs from the supplement rendering")
    _, record = figure_record(evidence)
    recorded = json.loads(FIGURE_MANIFEST.read_text())
    if recorded["inputs_sha256"] != record["inputs_sha256"] or recorded["figures"] != record["figures"]:
        raise ValueError("Figure inputs differ from the recorded figure manifest; rerun --write")
    for name in FIGURE_NAMES:
        if hashlib.sha256((FIGURES / name).read_bytes()).hexdigest() != recorded["png_sha256"][name]:
            raise ValueError(f"{name} differs from the recorded figure manifest")
